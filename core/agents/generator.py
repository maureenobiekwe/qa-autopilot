"""Phase 3b - Test generation. trace.json -> a runnable pytest-playwright file.

The generated test is plain Python a reviewer can read. Every element lookup goes
through smart_locator.resolve(), so locators self-heal at run time.
"""
from __future__ import annotations

import os
import pprint
import re
from typing import Any, Dict

HEADER = '''"""AUTO-GENERATED by qa-autopilot (generator.py). Goal: {goal}

Re-generate with: python orchestrator.py --project {project} --force
"""
import json
import os
import re
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
ROOT = PROJECT.parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("QA_HEAL_LOG", str(PROJECT / "outputs" / "heals.jsonl"))

from core.lib.env import load_env  # noqa: E402
from core.lib.smart_locator import resolve  # noqa: E402

load_env()
CFG = json.loads((PROJECT / "config.json").read_text(encoding="utf-8"))
CFG.setdefault("credentials", {{}})
CFG["credentials"]["username"] = os.getenv("QA_USERNAME", CFG["credentials"].get("username", ""))
CFG["credentials"]["password"] = os.getenv("QA_PASSWORD", CFG["credentials"].get("password", ""))
SHOTS = PROJECT / "screenshots" / "run"
SHOTS.mkdir(parents=True, exist_ok=True)


def val(text):
    """Fill {{credentials.username}}-style placeholders from config.json."""
    def sub(m):
        cur = CFG
        for part in m.group(1).split("."):
            cur = cur.get(part, "") if isinstance(cur, dict) else ""
        return str(cur)
    return re.sub(r"\\{{\\{{\\s*([\\w.]+)\\s*\\}}\\}}", sub, text)


def test_{slug}(page):
    page.set_default_timeout(60000)
    page.goto(CFG["base_url"], wait_until="domcontentloaded")
'''


def _slug(text: str) -> str:
    words = re.findall(r"[a-z0-9]+", text.lower())[:6]
    return "_".join(words) or "flow"


def generate(project_dir: str, workflow: Dict[str, Any], trace: Dict[str, Any]) -> str:
    project = os.path.basename(os.path.abspath(project_dir))
    lines = [HEADER.format(goal=workflow["goal"].replace('"""', "'"), project=f"projects/{project}", slug=_slug(workflow["goal"]))]
    for step in trace["steps"]:
        lines.append(f"    # step {step['n']}: {step['intent']}")
        for act in step["actions"]:
            kind = act["action"]
            if kind in ("fill", "select", "check", "click"):
                cands = pprint.pformat(act["candidates"], width=110, compact=True)
                indented = "\n".join("        " + ln for ln in cands.splitlines())
                lines.append(f"    el = resolve(page, (\n{indented}\n    ))")
                if kind == "fill":
                    lines.append(f"    el.fill(val({act['value']!r}))")
                elif kind == "select":
                    lines.append(f"    el.select_option(label={act['value']!r}) if {act['value']!r} else el.select_option(index=1)")
                elif kind == "check":
                    lines.append("    el.check()")
                else:
                    lines.append("    el.click()")
                lines.append("    page.wait_for_load_state('domcontentloaded')")
            elif kind == "assert_text":
                lines.append(f"    assert {act['value'].lower()!r} in page.inner_text('body').lower(), 'expected text not on page: ' + {act['value']!r}")
            elif kind == "assert_url":
                lines.append(f"    assert {act['value']!r} in page.url, 'unexpected url: ' + page.url")
        lines.append(f"    page.screenshot(path=str(SHOTS / 'step_{step['n']:02d}.png'))")
        lines.append("")
    tests_dir = os.path.join(project_dir, "tests")
    os.makedirs(tests_dir, exist_ok=True)
    path = os.path.join(tests_dir, "test_main.py")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return path
